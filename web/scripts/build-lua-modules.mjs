#!/usr/bin/env node
// Walks src/**/*.lua and emits web/src/lua-modules.generated.js, a JS module
// exporting { "modname.dotted": "<lua source>" } for every Prometheus source
// file. This lets the browser bundle preload real Prometheus Lua source into
// Fengari's package.preload table with zero runtime fetch/CORS concerns —
// everything ships inside the single static bundle.js.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const SRC_DIR = path.join(__dirname, "..", "..", "src");
const OUT_FILE = path.join(__dirname, "..", "src", "lua-modules.generated.js");

function walk(dir, base, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, base, out);
    } else if (entry.name.endsWith(".lua")) {
      const rel = path.relative(base, full);
      const modname = rel.slice(0, -4).split(path.sep).join(".");
      out[modname] = fs.readFileSync(full, "utf-8");
    }
  }
}

const modules = {};
walk(SRC_DIR, SRC_DIR, modules);

const count = Object.keys(modules).length;
if (count === 0) {
  console.error("No .lua files found under", SRC_DIR);
  process.exit(1);
}

const banner = `// AUTO-GENERATED by web/scripts/build-lua-modules.mjs — do not edit by hand.
// Contains the real, unmodified (except for 4 host-compat patches, see
// PATCHES.md) Prometheus obfuscator source, embedded for offline use.
`;

fs.writeFileSync(
  OUT_FILE,
  banner + "export const LUA_MODULES = " + JSON.stringify(modules, null, 0) + ";\n"
);

console.log(`Embedded ${count} Lua modules -> ${path.relative(process.cwd(), OUT_FILE)}`);
